const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs'); const os = require('node:os'); const path = require('node:path')
const room = require('../lesson-room')
function fixture (run) {
  const old = process.env.TEACHING_STATE_DIR; const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'lesson-publish-')); process.env.TEACHING_STATE_DIR = dir
  const teacher = { id: 'teacher', user: 'teacher' }
  const command = input => room.command(teacher, { revision: room.load().revision, ...input })
  try { command({ action: 'start' }); run(command, dir) } finally { if (old === undefined) delete process.env.TEACHING_STATE_DIR; else process.env.TEACHING_STATE_DIR = old; fs.rmSync(dir, { recursive: true, force: true }) }
}
test('whole-class publication works before attendance and survives a fresh process', () => fixture((command, dir) => {
  command({ action: 'assign', task: 'bridge', targets: 'all', note: '先读取卷轴' })
  let state = room.load(); assert.deepEqual(state.students, {}); assert.equal(state.gathered, true); assert.equal(state.paused, true)
  const persisted = JSON.parse(require('node:child_process').execFileSync(process.execPath, ['-e', "console.log(JSON.stringify(require('./teaching/lesson-room').load()))"], { cwd: path.join(__dirname, '../..'), encoding: 'utf8' }))
  assert.equal(persisted.assignments[0].task, 'bridge')
  room.join('2026010001'); const view = room.studentView('2026010001')
  assert.equal(view.offeredTask.id, 'bridge'); assert.equal(view.offeredTask.note, '先读取卷轴'); assert.equal(view.task.id, 'bridge')
  assert.throws(() => room.move('2026010001', view.id, 'next', view.offeredTask.assignmentId), /讲解/)
  command({ action: 'resume' }); room.move('2026010001', view.id, 'next', view.offeredTask.assignmentId)
  state = room.load(); assert.ok(state.assignments[0].accepted['2026010001']); assert.equal(room.studentView('2026010001').task.note, '先读取卷轴')
}))
test('targeted task delivery does not depend on attendance or accidentally change the class default', () => fixture(command => {
  room.join('2026010001')
  command({ action: 'assign', task: 'purify', targets: ['2026010001', '2026010002', '2026010002'] })
  assert.equal(room.load().assignments[0].targets.length, 2)
  room.join('2026010002'); room.join('2026010003')
  assert.equal(room.studentView('2026010002').offeredTask.id, 'purify')
  assert.equal(room.studentView('2026010003').task.id, 'basic'); assert.equal(room.studentView('2026010003').offeredTask, null)
  assert.equal(room.studentView('2026010001').task.id, 'basic')
  assert.throws(() => command({ action: 'assign', task: 'bridge', targets: ['__proto__'] }), /学号/)
  assert.throws(() => command({ action: 'assign', task: 'bridge', targets: [] }), /学号/)
  assert.throws(() => command({ action: 'assign', task: 'missing', targets: 'all' }), /有效任务/)
}))
test('publishing never ejects the current task or erases saved work; accepting a stale offer fails', () => fixture(command => {
  room.join('2026010001'); command({ action: 'resume' })
  const id = room.load().id; const store = room.store(id)
  store.saveProgress('2026010001', { 'local-python-34': { code: { 'hero-placeholder': { plan: 'label = readTag("货箱封签")' } }, teachingComplete: true } })
  room.record(id, '2026010001', 'local-python-34', { teachingComplete: true })
  command({ action: 'assign', task: 'bridge', targets: 'all' })
  const first = room.studentView('2026010001').offeredTask.assignmentId
  assert.equal(room.access('2026010001', 'local-python-34').allowed, true)
  assert.equal(room.access('2026010001', 'local-python-39').allowed, false)
  assert.equal(room.load().paused, false); assert.equal(room.load().gathered, false)
  command({ action: 'assign', task: 'loom', targets: 'all' })
  assert.throws(() => room.move('2026010001', id, 'next', first), /更新任务/)
  room.move('2026010001', id, 'next', room.studentView('2026010001').offeredTask.assignmentId)
  command({ action: 'assign', task: 'basic', targets: 'all' })
  room.move('2026010001', id, 'next', room.studentView('2026010001').offeredTask.assignmentId)
  assert.equal(store.readProgress('2026010001')['local-python-34'].teachingComplete, true)
  assert.equal(store.readProgress('2026010001')['local-python-34'].code['hero-placeholder'].plan, 'label = readTag("货箱封签")')
  assert.equal(room.studentView('2026010001').result.complete, true)
  command({ action: 'assign', task: 'basic', targets: 'all' }); room.move('2026010001', id, 'next')
  assert.equal(room.studentView('2026010001').result.complete, true)
}))
test('latest applicable assignment wins for both current and late students; end closes delivery', () => fixture(command => {
  command({ action: 'assign', task: 'bridge', targets: 'all' })
  command({ action: 'assign', task: 'rescue', targets: ['2026010001'] })
  room.join('2026010001'); room.join('2026010002')
  assert.equal(room.studentView('2026010001').offeredTask.id, 'rescue')
  assert.equal(room.studentView('2026010002').offeredTask.id, 'bridge')
  command({ action: 'assign', task: 'dispatch', targets: 'all' }); room.join('2026010003')
  for (const id of ['2026010001', '2026010002', '2026010003']) assert.equal(room.studentView(id).offeredTask.id, 'dispatch')
  command({ action: 'end' }); assert.throws(() => command({ action: 'assign', task: 'basic', targets: 'all' }), /没有正在进行/)
  command({ action: 'start' }); assert.deepEqual(room.load().assignments, [])
}))
