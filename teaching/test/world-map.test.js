const test = require('node:test')
const assert = require('node:assert/strict')
const designs = require('../map-designs')
const { compareLevels } = require('../curriculum')
const { routeFor } = require('../world-map')
const { nextTask } = require('../continuation')
const levels = designs.map(d => ({ slug: String(d.index), teachingMap: d })).sort(compareLevels)
test('all formal landmarks connect, optional branches stay off the main route and samples stay outside', () => {
  const { nodes, edges } = routeFor(levels)
  const main = levels.filter(l => !l.teachingMap.prototype && !l.teachingMap.optional)
  assert.equal(nodes.length, levels.filter(l => !l.teachingMap.prototype).length)
  assert.deepEqual(edges.filter(e => !e.branch).map(e => [e.from.slug, e.to.slug]), main.slice(1).map((to, i) => [main[i].slug, to.slug]))
  for (const node of nodes.filter(l => l.teachingMap.optional)) assert.ok(edges.some(e => e.branch && e.to === node))
  const hidden = routeFor(levels.filter(l => l.slug !== '26'))
  assert.ok(hidden.edges.every(e => e.from.slug !== '26' && e.to.slug !== '26'))
})
test('main continuation skips side quests and side quests continue only to open neighbors', () => {
  const releases = Object.fromEntries(levels.map(l => [l.slug, true]))
  const go = (id, state = releases) => nextTask(levels, String(id), { state: { complete: true }, codeHash: 'ok', scenePasses: { 0: { hash: 'ok' } } }, state)
  for (const [a, b] of [[10, 13], [14, 16], [26, 7], [11, 12], [33, 20], [20, 21]]) assert.equal(go(a).slug, String(b))
  assert.equal(go(11, { ...releases, 12: false }).slug, '13')
  assert.equal(go(10, { ...releases, 13: false }).kind, 'waiting')
  assert.equal(go(32).kind, 'finished')
  assert.equal(go(21).kind, 'finished')
})
